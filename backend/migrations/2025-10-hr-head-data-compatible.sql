-- 查询验证
SELECT 
    DATE(pl.created_at) as '日期',
    pl.title as '日志标题',
    pl.category as '类别',
    pl.quadrant as '象限',
    CASE WHEN pl.related_task_id IS NOT NULL THEN '是' ELSE '否' END as '关联任务'
FROM personal_logs pl
WHERE pl.user_id = 'dept-head-001'
    AND pl.created_at >= '2025-10-01'
    AND pl.created_at < '2025-11-01'
ORDER BY pl.created_at;

SELECT 
    t.title as '任务标题',
    t.priority as '优先级',
    t.status as '状态',
    t.deadline as '截止日期',
    t.progress_percentage as '进度',
    COUNT(pl.id) as '关联日志数'
FROM tasks t
LEFT JOIN personal_logs pl ON t.id = pl.related_task_id
WHERE t.assignee_id = 'dept-head-001'
    AND t.created_at >= '2025-10-01'
GROUP BY t.id, t.title, t.priority, t.status, t.deadline, t.progress_percentage
ORDER BY t.deadline;

